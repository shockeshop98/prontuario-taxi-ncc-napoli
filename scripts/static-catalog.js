window.prontuarioCatalogModel = function (item, type) {
  const model = window.prontuarioStaticCatalog[item.demoBaseCode || item.code];
  if (!model) throw Error(`Testo editoriale mancante: ${item.code}`);
  const title = type === 'NCC' ? 'con autorizzazione NCC n. […]' : 'con C.P. n. […]';
  const titleId = type === 'NCC' ? 'autorizzazione NCC n. […]' : 'C.P. n. […]';
  const subjectTitle = type === 'NCC' ? 'l’autorizzazione NCC n. […]' : 'la licenza C.P. n. […]';
  const titleNominative = type === 'NCC' ? 'L’autorizzazione NCC n. […]' : 'La licenza C.P. n. […]';
  const titleHolder = type === 'NCC' ? 'Il titolare dell’autorizzazione NCC n. […]' : 'Il titolare della licenza C.P. n. […]';
  const expand = value => value.replaceAll('%TITLE%', title).replaceAll('%TITLE_ID%', titleId).replaceAll('%SUBJECT_TITLE%', subjectTitle).replaceAll('%TITLE_NOMINATIVE%', titleNominative).replaceAll('%TITLE_HOLDER%', titleHolder).replaceAll('%TITLE_HOLDER_LOWER%', titleHolder.toLowerCase());
  return {
    ...model,
    lead: expand(model.lead),
    options: model.options.map(expand),
    other: expand(model.other),
    tail: expand(model.tail)
  };
};

window.prontuarioStaticLayout = function (catalog, manualParts, pageMap) {
  const variantItems = [
    ...window.prontuarioDemoCaseItems(catalog),
    ...window.prontuarioCatalogVariantItems(catalog)
  ];
  const byBase = new Map();
  for (const item of variantItems) {
    const key = item.demoBaseId;
    if (!byBase.has(key)) byBase.set(key, []);
    byBase.get(key).push(item);
  }
  const originals = new Map(catalog.map(item => [item.id, item]));
  const rowsPerIndexPage = 38;
  const sections = manualParts.map(part => {
    const type = part.type === 'equina' ? 'Trazione animale' : part.type === 'ncc' ? 'NCC' : 'Taxi';
    const rows = part.cases.filter(id => id !== 'nccserv' && id !== 'esposizionetariffario').flatMap(id => byBase.get(id) || [originals.get(id)]).map(item => ({item,type}));
    return {label:part.label,type,rows,indexPages:Math.ceil(rows.length/rowsPerIndexPage)};
  });
  const indexPageCount = sections.reduce((sum, section) => sum + section.indexPages, 0);
  const preservedIntroPages = [10,11,12,13,14];
  const firstCasePage = 1 + indexPageCount + preservedIntroPages.length + 1;
  const pages = {};
  const rows = sections.flatMap(section => section.rows);
  rows.forEach(({item,type},index) => {
    const key=`${item.id}/${type}`;
    pages[key]=pageMap?.[key]||firstCasePage+index;
  });
  for(const [alias,canonical] of Object.entries(window.prontuarioCatalogAliases)){
    const type=alias==='esposizionetariffario'?'Taxi':'NCC';
    pages[`${alias}/${type}`]=pages[`${canonical}/${type}`];
  }
  return {sections,rows,pages,indexPageCount,rowsPerIndexPage,preservedIntroPages,firstCasePage,variantItems};
};
